const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require('playwright');

(async () => {
  const baseURL = process.env.STUDYSEAT_TEST_URL || 'http://127.0.0.1:5057';
  const evidence = process.env.STUDYSEAT_EVIDENCE_DIR ? path.resolve(process.env.STUDYSEAT_EVIDENCE_DIR) : path.resolve(__dirname, '../evidence');
  fs.mkdirSync(evidence, { recursive: true });
  const browser = await chromium.launch({ headless: true, channel: process.env.STUDYSEAT_BROWSER_CHANNEL || 'msedge' });
  const context = await browser.newContext({ viewport: { width: 1360, height: 1000 } });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  try {
    await page.goto(new URL('/diagnostics', baseURL).href);
    await page.locator('#username').waitFor({ state: 'visible' });
    await page.screenshot({ path: path.join(evidence, 'login-desktop.png'), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({ path: path.join(evidence, 'login-mobile.png'), fullPage: true });
    await page.setViewportSize({ width: 1360, height: 1000 });
    await page.locator('#username').fill('832402116');
    await page.locator('#password').fill('wrong');
    await page.getByRole('button', { name: '登录', exact: true }).click();
    await page.getByRole('status').filter({ hasText: '账号或密码错误' }).waitFor();
    await page.locator('#password').fill('123456');
    await page.getByRole('button', { name: '登录', exact: true }).click();
    await page.locator('#welcome').filter({ hasText: '申子衡' }).waitFor();
    await page.locator('.room').first().waitFor();
    assert.equal(await page.locator('.room').count(), 4);
    const forbidden = await page.evaluate(async () => (await fetch('/api/v1/admin/audit-events')).status);
    assert.equal(forbidden, 403);
    const marker = `浏览器持久化验证 ${Date.now()}`;
    await page.locator('#note').fill(marker);
    await page.getByRole('button', { name: '保存到数据库' }).click();
    await page.locator('#notes').filter({ hasText: marker }).waitFor();
    await page.reload();
    await page.locator('#notes').filter({ hasText: marker }).waitFor();
    await page.screenshot({ path: path.join(evidence, 'student-dashboard.png'), fullPage: true });
    await page.getByRole('button', { name: '退出登录' }).click();
    await page.locator('#username').waitFor({ state: 'visible' });
    await page.locator('#username').fill('student02');
    await page.locator('#password').fill('Study1234');
    await page.getByRole('button', { name: '登录', exact: true }).click();
    await page.locator('#welcome').filter({ hasText: '学生 B' }).waitFor();
    await page.locator('#notes').filter({ hasText: '还没有验证记录' }).waitFor();
    await page.getByRole('button', { name: '退出登录' }).click();
    await page.locator('#username').waitFor({ state: 'visible' });
    await page.locator('#username').fill('admin01');
    await page.locator('#password').fill('Admin1234');
    await page.getByRole('button', { name: '登录', exact: true }).click();
    await page.locator('#events [data-action="PERSISTENCE_NOTE_CREATED"]').filter({ hasText: '保存验证文本' }).waitFor();
    await page.screenshot({ path: path.join(evidence, 'admin-dashboard.png'), fullPage: true });
    assert.deepEqual(errors, []);
    const report = { result: 'passed', executed_at: new Date().toISOString(), browser: await browser.version(), playwright: require('playwright/package.json').version, checks: ['desktop login', 'mobile no overflow', 'wrong password rejected', 'student login', '4 shared rooms', 'admin API returns 403 for student', 'note survives refresh', 'student B isolation', 'logout', 'admin audit data', 'no uncaught page errors'] };
    fs.writeFileSync(path.join(evidence, 'browser.json'), JSON.stringify(report, null, 2));
    console.log(JSON.stringify(report, null, 2));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
